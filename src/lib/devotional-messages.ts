export function getRandomDevotionalMessage(): string {
  if (devotionalMessages.length === 0) {
    return "لا توجد رسائل حاليًا.";
  }
  const randomIndex = Math.floor(Math.random() * devotionalMessages.length);
  return devotionalMessages[randomIndex];
}
